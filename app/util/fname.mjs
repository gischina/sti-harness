/**
 * 文件名净化 —— **安全件，必须单点**。
 *
 * 唯一职责：把一个"用户给的文件名"压成**不含任何目录成分**的安全基名，供拼接存储路径。
 *
 * 为什么必须单点（而不是各模块各留一份拷贝）：这一层是**防路径穿越 / 文件名注入**的
 * 唯一屏障，两份拷贝意味着「加固了一处、漏了另一处」是可能的 —— 而漏的那处不报错，
 * 只会在某个没人测到的上传名上被触发。历史体检（assessment-0.11.0 §A1-#4）把这条列为
 * 「五类真·逐字重复」里最该先修的一个，就是因为它同时是「重复」与「安全」。
 *
 * 规则（三处调用方口径必须完全一致）：
 *   1. 反斜杠先归一成正斜杠，再取最后一段 —— 吃掉 `..\..\etc\passwd` 这类；
 *   2. 只保留 `\w` / `.` / `-` / 中文，其余替换成 `_` —— 吃掉 `:` `*` `?` 等不合法字符；
 *   3. 截断到 120 字符；
 *   4. 全被吃光（或本来就是空）时，退回调用方给的 fallback。
 *
 * ⚠️ 本函数**不做**去重、不校验扩展名、不判空内容 —— 它只管"这个字符串能不能安全地
 *    当作一个路径末段"，其余是调用方的语义。
 *
 * Copyright 2026 liwei（易智瑞西安）.
 */

/**
 * @param {unknown} filename 用户提供的原始文件名（可能含目录、非法字符、超长）
 * @param {string} [fallback] 净化后为空时的兜底基名（各调用方给各自的语义，如 'attachment'）
 * @returns {string} 可安全拼接进路径的基名（非空）
 */
export function safeBaseName(filename, fallback = 'file') {
  const s = String(filename == null ? '' : filename).replace(/\\/g, '/');
  const base = s.slice(s.lastIndexOf('/') + 1) || fallback;
  return base.replace(/[^\w.\-\u4e00-\u9fff]+/g, '_').slice(0, 120) || fallback;
}
