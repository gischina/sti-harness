-- ---------------------------------------------------------------------------
-- 0018 · 账号登录退避状态落库
--
-- 为什么加这张表（2026-10 安全评审 P0-4）：
--   登录失败计数原本放在 identity/service.mjs 的进程内 Map 里。后果是
--   **服务重启即清零** —— 攻击者每跑一阵就等到平台重启（或主动把它打重启），
--   退避对他而言形同虚设；多进程部署时计数也不共享。
--
--   本表把「同一账号连续失败次数」与「锁定截止时间」持久化：
--   fail_count 达阈值后写 locked_until（ISO 时间），过期即自动解锁，
--   登录成功直接删行。语义与内存版逐字一致，只是不再随重启丢失。
--
-- 三条纪律：
--   1. **账号级而非密码级**：不知道账号是否存在时，探测也照样计数，
--      不泄露"账号是否存在"，与内存版同口径。
--   2. **不建外键到 organizations**：与审计、通知投递同纪律 ——
--      删组织时这些残留行由清理任务负责，不让一条退避记录挡住组织删除。
--   3. **锁定期存在这一行本身不暴露账号存在性**：登录入口对所有失败
--      统一返回"账号或口令不正确"，不区分"已锁定"与"密码错"。
--
-- 只增不改（迁移纪律）：新增迁移，不动历史迁移。
--
-- Copyright 2026 liwei（易智瑞西安）.
-- ---------------------------------------------------------------------------

CREATE TABLE login_lockout (
  tenant_id    TEXT    NOT NULL,
  username     TEXT    NOT NULL,
  fail_count   INTEGER NOT NULL DEFAULT 0,
  locked_until TEXT,
  updated_at   TEXT    NOT NULL,
  PRIMARY KEY (tenant_id, username)
);
