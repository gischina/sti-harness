-- 0015 · 移除僵尸列 `users.is_admin`（消除冗余真相）
--
-- 为什么删（一次全量体检抓出）：
--   0001 建表起就有 `is_admin`，且每次建用户 / 改角色 / 改组角色都**写**它
--   （旧 `refreshAdminFlags` → `updateUser({is_admin})`）。但**没有任何权限判定读它**：
--   `identity/service.mjs` 自己写明「真源只有 `role_bindings` 一处，读物化列就是
--   多一份可能漂移的真相」。前端也不读；唯一读它的 `countActiveAdmins` 是死函数。
--   → 这是一份"维护着、却从不被用于决策"的冗余数据。项目注释里担心的
--     「列里写 0、实际能管平台」这类不一致，**这列就正处于这个状态**：
--     因为没人读，所以不报错，只是持续腐烂。
--
-- 处置（论证见 assessment-1.2.0.md A3）：**彻底删除**，而不是"停写但保留" ——
--   本项目已在迁移层做版本化升级，"保留列以兼容历史库"在这里没有必要；
--   留下的空列只会继续被误读。删掉之后，"谁是管理员"只有 `role_bindings` 一个来源。
--
-- 只增不改（迁移纪律）：
--   · 这是**新增**迁移，不改 0001（改历史迁移会断校验和、卡死启动）。
--   · `users` 被 `auth_sessions.user_id` / `group_members.user_id` / `role_bindings`
--     引用，但 SQLite 的 DROP COLUMN 允许被外键引用的表删**非键、非唯一、非索引**
--     的列（该列不属于任何约束）；删列会重写该表，数据保留。
--
-- Copyright 2026 liwei（易智瑞西安）.
-- ---------------------------------------------------------------------------

ALTER TABLE users DROP COLUMN is_admin;
