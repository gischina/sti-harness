-- 工具级可见性绑定。⚠️ 连同 `mcp:` 前缀那一族一起清：
-- MCP 服务的跨租户 deny 曾经写在同一列上（capability_type 仍是 'tool'），
-- 语义上属于工具那套判定 —— 0025 起 MCP 走自己的判定，这些残留行不再被读。
DELETE FROM capability_bindings WHERE capability_type = 'tool';

DROP TABLE IF EXISTS tools;
