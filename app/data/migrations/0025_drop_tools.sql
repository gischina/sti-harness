-- 0025 · 删掉「工具登记表」（tools 表 + 工具级的可见性绑定）
--
-- 删什么：
--   1. `tools` 表整表（name / origin / enabled / policy_json / meta_json）；
--   2. `capability_bindings` 里 `capability_type = 'tool'` 的绑定
--      （以及 MCP 服务可见性曾经复用过的写在同一列上的 `mcp:<name>` 那一族）。
--
-- 为什么删（用户裁定，2026-10-08）：
--   用户原话：「工具是在内核自己调用，不用单独写这个能力，而且不会单独列出来有哪些工具」。
--
--   这句话把之前那个设计的前提直接推翻了。三条事实：
--     · **工具由内核自己调用**。平台侧没有任何工具执行路径（0.16.2 就拆掉了
--       "平台主动发起工具执行"那一族），平台命令不了工具、也拦不住工具；
--     · **没有可登记的对象**。上游 wire 契约里**没有工具清单 RPC**，
--       `compat/*.mjs` 那份候选探测（`tools/list`、`capabilities/tools`、
--       `pluginInventory/tools`、`tool/list`）实测**全部 404**。工具只以
--       `tool-call` / `tool-result` 事件的形式**事后**出现在会话事件流里；
--     · 因此**没有"有哪些工具"这个问题**。能回答的只有"这一轮调了什么"，
--       而那是事件流事实，不是清单。
--
--   于是"工具"与 Skill 的根本差别成立：**Skill 是平台可治理的能力**
--   （有安装流程、有文件落位、有登记表、能逐个启停），**工具不是** ——
--   它没有独立的存在形式，只是内核内部的一次调用。此前把它跟 Skill / MCP 并列为
--   "三类可治理能力"是错把"事件流里出现过的东西"当成了"可以登记的东西"。
--
-- 删完之后谁在把门：
--   · **Skill 闸原样保留**（`capability-gate.mjs` 的 `gated.listSkills`）；
--   · **MCP 闸改为走自己那套判定**。⚠️ 这一条是本次最需要小心的地方：
--     MCP 服务的可见性此前**复用了工具判定函数**（`toolVisibleNow('mcp:'+name)`），
--     只按工具名停用/放开。工具那套一去，MCP 必须自己独立判定 —— 否则
--     "删了工具"会顺手把 MCP 的可见性闸一起弄坏，而那是另一个功能。
--   · 路由层仍由 `skill:read` / `skill:write` 把守。
--   **门禁没有消失，消失的是"工具可以被单独停用"这一层。**
--
-- 数据影响说清（**不可逆**）：
--   · 登记过的工具及其启停状态**无法恢复**（迁移不做备份）。
--     代价接近零：那张表在真上游下**本来就是空的**（`listTools()` 恒返回空，
--     因为上游没有这个 RPC），有内容的只可能是测试替身与手工注册；
--   · **会话与事件一行不动** —— 历史回合里"调过某个工具"这个事实活在
--     `events` 表的 `tool-call` / `tool-result` 事件里，不在 tools 表里。
--     所以"这一轮调了什么"在删除后**照常可查、照常可显示**。
--
-- ⚠️ **只增不改**（迁移纪律）：0001_init.sql 里那张 tools 表的建表语句
--    **一个字都不能动** —— migrate.mjs 对已应用迁移做 sha256 比对，改了会硬失败。
--    **因此"新库一建出来就没有 tools 表"这件事由本迁移负责，不靠改 0001 表达** ——
--    新装流程同样是"跑完全部迁移"，0001 建出来、0025 立刻 DROP 掉，终态一致。
--    （本迁移初稿曾顺手删掉 0001 里的建表语句，直接后果是**本机库启动即硬失败**
--     ——`已应用的迁移 0001_init.sql 内容已被修改`。这就是那条纪律存在的意义：
--    改 0001 不会让任何一台已经跑过的机器"升级"，只会让它们**全部起不来**。）
--
-- ⚠️ 顺序：先删绑定再删表。绑定表的 capability_id 存的是**工具名**而不是外键，
--    所以反过来也能跑通 —— 但按依赖方向删（引用的先走）读起来才是对的顺序。
