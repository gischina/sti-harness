-- 0017 · 会话挂载知识库（把"企业知识"接进对话）
--
-- 为什么加这一列：
--   0.13.1 及以前，知识库是一个**孤立的检索工具** —— 能建库、能导入、能检索、
--   能做召回测试，但对话工作台**没有任何挂库入口**，routes/kernel.mjs 不传库参数，
--   内核 provider 更是**零处引用 knowledge**。于是"企业知识"与"智能体"这两件
--   本该连在一起的事各跑各的：客户最朴素的那句"把我的制度手册喂进去，它就照着答"
--   在整个系统里找不到一条可执行的路径。
--
--   本列记录**这个会话挂在哪些知识库上**（JSON 数组文本）。
--   空数组 = 不挂库，**行为与 0.13.1 逐字不变**（不检索、不注入、不新增任何事件帧）。
--
-- 实现路线（重要）：
--   检索在**平台侧**发生，命中片段拼进本轮上下文（见 routes/kernel.mjs 的
--   composeWithKnowledge），**刻意不走"把检索注册成工具给模型调用"那条路** ——
--   平台侧工具执行在真实内核上并不存在（assessment-0.11.0 §B7：wire 契约不提供
--   平台发起的工具执行），那条路会立刻卡在同一道墙上。上下文注入只依赖
--   "平台能往本轮 content 里写字"这一件事，而附件正文注入（0.10.0）已经证明它成立。
--
-- 四条纪律（改这一列时请一起读）：
--   1. **它是一份"声明"，不是观测** —— 与 model_id 同源：记录的是"平台按这些库
--      检索过"，不是"模型一定读了这些库"。命中数、引用与耗时在事件帧里如实回传，
--      取不到就报空，**不做乐观补全**。
--   2. **挂库 ≠ 可见**：检索仍走 knowledge.search 的库级 ACL（visibleBases 过滤 +
--      逐个校验，不可见的库直接忽略并记 note）。库后来被改成 restricted 而该用户
--      无权 → 检索自动忽略那一份，**不泄漏内容、也不打断对话**。
--   3. **不建外键**：与审计、通知投递同一条纪律 —— 删一个知识库不该被"有会话挂着它"
--      挡住，也不该级联删掉会话；悬空 id 由检索侧当作"不可见"静默忽略。
--   4. **用 JSON 数组而不是关联表**：会话挂库是**会话级配置**（通常 0~几个），
--      与 model_provider / model_id 同层。一旦出现"按库反查会话"这类需求，
--      再升维成关联表，届时走新迁移 —— 不提前为想象中的查询建表。
--
-- 只增不改（迁移纪律）：这是**新增**迁移，不动 0001。
-- SQLite 的 ADD COLUMN 允许带常量默认值的 NOT NULL 列，已有会话自动回填为 '[]'。
--
