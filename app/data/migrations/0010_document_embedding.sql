-- 0010 · 文档的向量来源（向量一致性）
--
-- 为什么需要（这是一个**因为 P1-1 才从理论变成现实**的问题）：
--   在模型中心（P1-1）之前，向量模型只能写在 `data/config.json` 里，
--   换模型意味着改配置 + 重启，是个低频且需要动文件的操作，"换到一半"的概率很低。
--   现在默认向量模型可以在页面上点一下切换 —— 于是出现了一个新状态：
--   **同一个知识库里，早期文档用模型 A 嵌入、之后导入的文档用模型 B 嵌入。**
--   检索时两种向量被放进同一个数组里算余弦相似度 —— 数学上能算出数，
--   语义上**毫无意义**，而且**没有任何报错**：结果只是"变差了"。
--   这是最难被发现的一类质量问题（没有人会怀疑"检索结果不对"是因为向量不同源）。
--
--   本迁移把"这篇文档是用哪个模型嵌入的"记下来，让这种不一致**可见**：
--   · 知识库页面可以据此提示"库内有 N 篇文档由不同模型嵌入，建议重建"；
--   · `reindexBase()`（P1-2）能据此只重建需要重建的文档。
--
-- 只增不改（迁移纪律）：与 0002 同款，用 ALTER TABLE ADD COLUMN 追加，
-- 不动 0001 的历史定义。已有文档的这三列为空字符串/0 —— 表示"未知来源"，
-- **不为历史数据编造模型名**（那会让页面显示一个错误的确定性答案）。
--
-- Copyright 2026 liwei（易智瑞西安）.
-- ---------------------------------------------------------------------------

ALTER TABLE documents ADD COLUMN embedding_provider TEXT NOT NULL DEFAULT '';  -- openai-compat | ollama | ''
ALTER TABLE documents ADD COLUMN embedding_model    TEXT NOT NULL DEFAULT '';  -- 嵌入时实际使用的模型名
ALTER TABLE documents ADD COLUMN embedding_dim      INTEGER NOT NULL DEFAULT 0; -- 实际观察到的维度（0 = 未向量化）
